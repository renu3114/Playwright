
let a = 10;
let b = 25;
let c = 15;

if (a > b && a > c) {
    console.log("A is the largest number");
}
else if (b > a && b > c) {
    console.log("B is the largest number");
}
else if (c > a && c > b) {
    console.log("C is the largest number");
}
else {
    console.log("Two or more numbers are equal");
}
