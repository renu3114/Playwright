import { test, expect } from '@playwright/test';

test('test', async ({ page }) => {
  await page.goto('https://demowebshop.tricentis.com/');
  await page.getByRole('link', { name: 'Log in' }).click();
  await page.getByRole('textbox', { name: 'Email:' }).click();
  await page.getByRole('textbox', { name: 'Email:' }).fill('renukamani1999@gmail.com');
  await page.getByRole('textbox', { name: 'Password:' }).click();
  await page.getByRole('textbox', { name: 'Password:' }).fill('Renuka@1499');
  await page.getByRole('button', { name: 'Log in' }).click();
  await page.getByRole('listitem').filter({ hasText: 'Poor' }).click();
  await page.getByRole('link', { name: 'Books' }).first().click();
  await page.locator('#products-orderby').selectOption('https://demowebshop.tricentis.com/books?orderby=11');
  await page.goto('https://demowebshop.tricentis.com/books?orderby=11');
  await page.locator('#products-pagesize').selectOption('https://demowebshop.tricentis.com/books?orderby=11&pagesize=12');
  await page.goto('https://demowebshop.tricentis.com/books?orderby=11&pagesize=12');
  await page.locator('#products-viewmode').selectOption('https://demowebshop.tricentis.com/books?orderby=11&pagesize=12&viewmode=list');
  await page.goto('https://demowebshop.tricentis.com/books?orderby=11&pagesize=12&viewmode=list');
  await page.getByRole('button', { name: 'Add to cart' }).nth(2).click();
  await page.getByRole('link', { name: 'Shopping cart (9)' }).click();
  await page.getByLabel('Country:').selectOption('41');
  await page.getByRole('button', { name: 'Checkout' }).click();
  await page.locator('.ui-resizable-handle.ui-resizable-ne').click();
  await page.getByRole('dialog', { name: 'Terms of service' }).click();
  await expect(page.locator('#termsofservice')).not.toBeChecked();
  await page.locator('#termsofservice').check();
  await page.getByRole('button', { name: 'Checkout' }).click();
  await page.getByRole('textbox', { name: 'City:' }).click();
  await page.getByRole('textbox', { name: 'City:' }).fill('bangalore');
  await page.getByRole('textbox', { name: 'Address 1:' }).click();
  await page.getByRole('textbox', { name: 'Address 1:' }).fill('bangalore');
  await page.getByRole('textbox', { name: 'Zip / postal code:' }).click();
  await page.getByRole('textbox', { name: 'Zip / postal code:' }).fill('560037');
  await page.getByRole('textbox', { name: 'Phone number:' }).click();
  await page.getByRole('textbox', { name: 'Phone number:' }).fill('9663331968');
  await page.getByRole('button', { name: 'Continue' }).click();
  await expect(page.getByLabel('Country:')).toHaveValue('0');
  await page.getByLabel('Country:').selectOption('41');
  await page.getByRole('button', { name: 'Continue' }).click();
});